import type { MatrixRow } from '~/types/drift'

export interface ZodCompilerOptions {
  clientPrefix?: string
  framework?: 'nextjs' | 'nuxtjs' | 'node'
}

export function compileZodSchema(
  matrix: MatrixRow[],
  options: ZodCompilerOptions = {}
): { tsCode: string; serverKeysCount: number; clientKeysCount: number } {
  const clientPrefix = options.clientPrefix || (options.framework === 'nuxtjs' ? 'NUXT_PUBLIC_' : 'NEXT_PUBLIC_')

  const serverFields: string[] = []
  const clientFields: string[] = []
  let serverKeysCount = 0
  let clientKeysCount = 0

  for (const row of matrix) {
    const isClient = row.key.startsWith(clientPrefix) || row.key.startsWith('PUBLIC_') || row.key.startsWith('VITE_')

    // Find first non-empty value across stages to deduce best type & default
    const cellEntries = Object.values(row.values)
    const validCell = cellEntries.find((c) => c.exists && c.value.trim() !== '')
    const sampleValue = validCell ? validCell.value : ''
    const inferredType = validCell ? validCell.inferredType : 'string'

    let zodValidator = 'z.string().min(1)'

    if (inferredType === 'number') {
      const numVal = Number(sampleValue)
      if (!isNaN(numVal)) {
        zodValidator = `z.coerce.number().default(${numVal})`
      } else {
        zodValidator = `z.coerce.number()`
      }
    } else if (inferredType === 'boolean') {
      const boolVal = sampleValue.toLowerCase() === 'true' || sampleValue === '1'
      zodValidator = `z.string().transform((val) => val === 'true' || val === '1').pipe(z.boolean()).default(${boolVal})`
    } else if (inferredType === 'url') {
      zodValidator = `z.string().url()`
    } else if (inferredType === 'email') {
      zodValidator = `z.string().email()`
    } else {
      if (row.key === 'NODE_ENV') {
        zodValidator = `z.enum(['development', 'test', 'staging', 'production']).default('development')`
      } else if (sampleValue && sampleValue.length < 50 && !row.key.includes('SECRET') && !row.key.includes('KEY')) {
        zodValidator = `z.string().min(1)`
      } else {
        zodValidator = `z.string().min(1)`
      }
    }

    const commentBlock = row.comment ? `  /** ${row.comment.replace(/\*\//g, '* /')} */\n` : ''
    const fieldDeclaration = `${commentBlock}  ${row.key}: ${zodValidator},`

    if (isClient) {
      clientFields.push(fieldDeclaration)
      clientKeysCount++
    } else {
      serverFields.push(fieldDeclaration)
      serverKeysCount++
    }
  }

  const isNuxt = options.framework === 'nuxtjs'

  const tsCode = `import { createEnv } from '@t3-oss/env-core'
import { z } from 'zod'

/**
 * Autogenerated Type-Safe Environment Schema
 * Compiled by EnvDrift Studio
 */
export const env = createEnv({
  server: {
${serverFields.length > 0 ? serverFields.join('\n') : '    // No server variables declared'}
  },
  clientPrefix: '${clientPrefix}',
  client: {
${clientFields.length > 0 ? clientFields.join('\n') : '    // No client variables declared'}
  },
  runtimeEnv: process.env,
  emptyStringAsUndefined: true,
})
`

  return {
    tsCode,
    serverKeysCount,
    clientKeysCount,
  }
}
